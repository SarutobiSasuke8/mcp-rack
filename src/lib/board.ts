/**
 * The board's server list, derived from servers.json: the facts each row on
 * /servers/ shows, in board order. scripts/generate-board.mjs renders these
 * rows as the Markdown board in README.md, and scripts/check-output.mjs parses
 * the built /servers/ and home pages and fails the build unless their rows
 * (as rendered by ServerRow.astro) equal these exactly.
 */
interface BoardSource {
  readonly slug: string;
  readonly name: string;
  readonly tagline: string;
  readonly lang: string;
  readonly transport: string;
  readonly status: string;
  readonly registry: string | null;
  readonly package: { readonly kind: string; readonly name: string; readonly version?: string | null | undefined } | null;
  readonly repo: string | null;
  readonly install: string | null;
  readonly order: number;
}

export interface BoardRow {
  readonly position: string;
  readonly slug: string;
  readonly name: string;
  readonly tagline: string;
  readonly lang: string;
  readonly transport: string;
  readonly status: string;
  readonly registryLabel: 'In registry' | 'Not listed yet';
  readonly packageLabel: string;
  readonly hasInstall: boolean;
}

export function registryLabel(registry: string | null): BoardRow['registryLabel'] {
  return registry ? 'In registry' : 'Not listed yet';
}

/** "pypi gimp-agent-mcp 0.5.0", or "source only" / "private preview" when unpackaged. */
export function packageLabel(server: Pick<BoardSource, 'package' | 'repo'>): string {
  if (!server.package) return server.repo ? 'source only' : 'private preview';
  return [server.package.kind, server.package.name, server.package.version].filter(Boolean).join(' ');
}

export function boardRows(servers: readonly BoardSource[]): BoardRow[] {
  return [...servers]
    .sort((a, b) => a.order - b.order)
    .map((s, i) => ({
      position: String(i + 1).padStart(2, '0'),
      slug: s.slug,
      name: s.name,
      tagline: s.tagline,
      lang: s.lang,
      transport: s.transport,
      status: s.status,
      registryLabel: registryLabel(s.registry),
      packageLabel: packageLabel(s),
      hasInstall: Boolean(s.install),
    }));
}

const cell = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ');

export function boardMarkdown(rows: readonly BoardRow[], siteUrl: string): string {
  const base = siteUrl.replace(/\/$/, '');
  const lines = [
    '| # | Server | What it does | Stack | Transport | Status | Registry | Package |',
    '|---|---|---|---|---|---|---|---|',
    ...rows.map((r) =>
      `| ${r.position} | [${cell(r.name)}](${base}/servers/${r.slug}/) | ${cell(r.tagline)} | ${r.lang} | ${cell(r.transport)} | ${r.status} | ${r.registryLabel} | ${cell(r.packageLabel)} |`,
    ),
  ];
  return lines.join('\n');
}

export const BOARD_START = '<!-- board:start (generated by `npm run board` from src/content/servers.json; do not edit by hand) -->';
export const BOARD_END = '<!-- board:end -->';

/** Replace the generated block in a README, or throw if the markers are missing. */
export function spliceBoard(readme: string, table: string): string {
  const start = readme.indexOf(BOARD_START);
  const end = readme.indexOf(BOARD_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error('README.md is missing the board markers.');
  }
  return `${readme.slice(0, start + BOARD_START.length)}\n\n${table}\n\n${readme.slice(end)}`;
}
